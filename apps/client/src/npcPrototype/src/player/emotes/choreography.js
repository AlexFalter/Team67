const ease=t=>t*t*(3-2*t),mix=(a,b,t)=>a.map((v,i)=>Array.isArray(v)?mix(v,b[i],t):v+(b[i]-v)*t);
export function sampleDance(id,time){
 const dance=choreography[id],phase=(time%dance.duration)/dance.duration*dance.poses.length,index=Math.floor(phase),a=dance.poses[index],b=dance.poses[(index+1)%dance.poses.length];
 // Robot locks most of each beat; the transition is brief but still continuous.
 const t=ease(dance.robot?Math.max(0,(phase-index-.65)/.35):phase-index);
 return Object.fromEntries(Object.keys(a).map(key=>[key,mix(a[key],b[key],t)]));
}
